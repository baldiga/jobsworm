"""RevHub, a curated GTM jobs feed.

`https://jobs.revhub.club/jobs.json` is a static JSON file published by a
community that collects go-to-market roles — SDR, AE, RevOps, Customer Success,
Sales Leadership, Marketing — out of WhatsApp groups and republishes them with
the sender's own apply link attached.

## Why it is worth having

The index is strong on engineering and thin on the commercial side of a tech
company. This feed is 100% that side, it is human-curated rather than scraped,
and it is free. Thirty-two jobs is small, but they are thirty-two jobs that
appear nowhere else in the index.

## Why it may import nothing

Read live on 2026-09-09:

    generated_at   2026-08-13   (27 days old)
    jobs           32
    posted_at      30 to 85 days old
    within 30 days 1

The feed is regenerated by hand and has not been regenerated in a month. This
project caps social and community postings at 30 days, so today almost the whole
file is already past the cap and is meant to be dropped. That is the cap working,
not the adapter failing. When the feed is refreshed the same code picks up the
new rows with no change.

## Privacy

This is the part that decides how the mapping is written.

The feed carries `contact.email`, `contact.phone` and `contact.linkedin` — six of
the thirty-two rows have at least one — because it was assembled from WhatsApp
messages where a person said "send me your CV". Those are individuals' personal
contact details, republished for a different purpose than ours. **They are read
and discarded here, deliberately, and never reach the database.** Only
`contact.url`, an employer's own careers page, is kept.

The identifiers have the same problem in a less obvious form. A row's `id` and
`source_message_id` can be a WhatsApp LID:

    job-0:10000000000000@lid:0000000000000000000A-0   (shape only; not a real id)

That number identifies a WhatsApp account — a person. It is not stored either.
The external id is a salted hash of it, which is stable across imports (so the
same job updates rather than duplicating) while carrying nothing back to whoever
sent the message. This follows the same rule the Facebook pipeline already
applies to poster names: the hash goes in, the identity does not.

A row whose only apply route was a personal email or phone number is dropped
rather than published with the contact stripped out, because a job posting with
no way to apply wastes the reader's time.
"""

from __future__ import annotations

import hashlib
import os
import re
from typing import Any, Iterator

import httpx

from ..ladder import USER_AGENT
from ..store import ScrapedJob

BASE = "https://jobs.revhub.club"
FEED = f"{BASE}/jobs.json"

HEADERS = {
    "Accept": "application/json",
    "User-Agent": USER_AGENT,
}

# A LID is the identifier WhatsApp gives an account. Any id containing one is
# hashed rather than stored, and this pattern is what recognises it.
_LID = re.compile(r"\d{6,}@lid", re.I)


class FeedError(RuntimeError):
    pass


def _clean(value: Any) -> str:
    return str(value or "").strip()


def _external_id(raw: str) -> str:
    """Stable, non-identifying id.

    Salted with POSTER_HASH_SALT, the same secret the Facebook pipeline uses, so
    the hash cannot be reversed by anyone who guesses the input format. Ids with
    no personal identifier in them are passed through unchanged — hashing a
    harmless id would only make the data harder to debug.
    """
    if not _LID.search(raw):
        return raw
    salt = os.environ.get("POSTER_HASH_SALT", "")
    return "wa-" + hashlib.sha256((salt + raw).encode("utf-8")).hexdigest()[:24]


def to_job(row: dict[str, Any]) -> ScrapedJob | None:
    """Map one feed row, or return None when it should not be published."""
    raw_id = _clean(row.get("id"))
    title = _clean(row.get("title"))
    if not raw_id or not title:
        return None

    contact = row.get("contact") or {}
    # ONLY the url. email, phone and linkedin are read and dropped on purpose;
    # see the module docstring.
    apply_url = _clean(contact.get("url"))
    if not apply_url:
        return None

    company = _clean(row.get("company"))
    summary = _clean(row.get("summary"))

    parts = [f"<p>{summary}</p>"] if summary else []
    fn = _clean(row.get("function"))
    seniority = _clean(row.get("seniority"))
    detail = " · ".join(p for p in (fn if fn != "Other" else "", seniority) if p)
    if detail:
        parts.append(f"<p>{detail}</p>")
    body = "".join(parts)
    if not body:
        return None

    return ScrapedJob(
        external_id=_external_id(raw_id),
        title=title,
        description_html=body,
        location_raw=_clean(row.get("location")),
        apply_url=apply_url,
        source="revhub",
        company_name=company or None,
        posted_at=_clean(row.get("posted_at")) or None,
        company_hidden=not company,
        meta={
            # The feed's own function label. Kept because it is stated by a human
            # who read the posting, which beats inferring it from one sentence.
            "feed_function": fn or None,
            "feed_seniority": seniority or None,
            "remote": bool(row.get("remote")),
            "company_domain": _clean(row.get("company_domain")) or None,
            "featured": bool(row.get("featured")),
        },
    )


def fetch(timeout: float = 30.0) -> dict[str, Any]:
    with httpx.Client(timeout=timeout, headers=HEADERS, follow_redirects=True) as client:
        r = client.get(FEED)
        if r.status_code >= 400:
            raise FeedError(f"revhub feed HTTP {r.status_code}: {r.text[:180]}")
        try:
            return r.json()
        except ValueError as exc:
            raise FeedError(f"revhub feed returned non-JSON: {exc}") from exc


def iter_jobs(max_jobs: int | None = None) -> Iterator[ScrapedJob]:
    """Yield mapped postings. The whole feed is one small file, so no paging."""
    payload = fetch()
    seen = 0
    for row in payload.get("jobs") or []:
        job = to_job(row)
        if not job:
            continue
        yield job
        seen += 1
        if max_jobs and seen >= max_jobs:
            return


def generated_at(payload: dict[str, Any]) -> str | None:
    """When the publisher last rebuilt the file. Worth logging: it goes stale."""
    return _clean(payload.get("generated_at")) or None
