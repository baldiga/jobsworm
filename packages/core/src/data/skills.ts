/** alias (lowercase) -> canonical term. */
export const SKILL_INDEX: Map<string, string> = (() => {
  const m = new Map<string, string>();
  for (const s of SKILLS) {
    for (const a of [s.term, ...s.aliases]) {
      const key = a.toLowerCase().trim();
      if (key && !m.has(key)) m.set(key, s.term);
    }
  }
  return m;
})();

export const SKILL_CATEGORY: Map<string, SkillCategory> = new Map(
  SKILLS.map((s) => [s.term, s.category]),
);

export const SKILL_TERM_COUNT = SKILLS.length;
export const SKILL_ALIAS_COUNT = SKILL_INDEX.size;
